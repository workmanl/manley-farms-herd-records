// Local release inventory generator. Run after changing any app asset.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../app/", import.meta.url);
const scope = process.env.HERD_BASE_PATH || "/tools/herd-records/";
if (!/^\/(?:[a-zA-Z0-9_-]+\/)*$/.test(scope))
  throw Error("Use an absolute directory path ending in /.");
await writeFile(
  new URL("manifest.webmanifest", root),
  JSON.stringify(
    {
      id: scope,
      name: "Manley Farms Herd Records",
      short_name: "Herd Records",
      display: "standalone",
      start_url: scope,
      scope,
      theme_color: "#1a1f16",
      background_color: "#1a1f16",
      icons: [
        {
          src: "icons/herd.svg",
          sizes: "any",
          type: "image/svg+xml",
          purpose: "any",
        },
        {
          src: "icons/herd-192.png",
          sizes: "192x192",
          type: "image/png",
          purpose: "any",
        },
        {
          src: "icons/herd-512.png",
          sizes: "512x512",
          type: "image/png",
          purpose: "any",
        },
        {
          src: "icons/herd-maskable.png",
          sizes: "512x512",
          type: "image/png",
          purpose: "maskable",
        },
      ],
    },
    null,
    2,
  ) + "\n",
);
const files = (await readdir(root, { recursive: true, withFileTypes: true }))
  .filter((e) => e.isFile())
  .map(
    (e) => (e.parentPath || e.path).slice(root.pathname.length) + "/" + e.name,
  )
  .map((p) => p.replace(/^\//, ""))
  .filter((p) => p !== "precache.js")
  .sort();
const assets = [];
for (const path of files)
  assets.push({
    path,
    sha256: createHash("sha256")
      .update(await readFile(new URL(path, root)))
      .digest("hex"),
  });
const { version: appVersion } = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const version = appVersion + ":" + createHash("sha256")
  .update(JSON.stringify(assets))
  .digest("hex")
  .slice(0, 20);
await writeFile(
  new URL("precache.js", root),
  `// Generated by scripts/build-pwa.mjs. No herd records.\nself.HERD_RELEASE = ${JSON.stringify({ version, schema: 1, assets }, null, 2)};\n`,
);
console.log(
  `${assets.length} local assets, release ${version}, scope ${scope}`,
);
